#!/usr/bin/env node
// Merge phase-1 semantic reader outputs + orchestrator adjudications → docs/spec/inventory/SEMANTIC.md
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url'
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..')
const DIR = path.join(ROOT, 'docs/spec/inventory/semantic')
const ADJ = JSON.parse(fs.readFileSync(path.join(ROOT, 'docs/spec/inventory/adjudications.json'), 'utf8'))
const files = fs.readdirSync(DIR).filter((f) => f.endsWith('.json')).sort()
const all = files.map((f) => JSON.parse(fs.readFileSync(path.join(DIR, f), 'utf8')))
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')
const md = ['# SEMANTIC INVENTORY (generated by tools/merge-semantic.mjs — do not hand-edit)', '',
  'Reader claims are **unadjudicated** unless the verdict column says otherwise. Reader reliability (orchestrator spot-checks) in `adjudications.json` → `readers`.', '']
md.push('## Reader reliability', '', '| reader | checked | confirmed | refuted | policy |', '|---|---|---|---|---|')
for (const [r, v] of Object.entries(ADJ.readers)) md.push(`| ${r} | ${v.checked} | ${v.confirmed} | ${v.refuted} | ${esc(v.policy)} |`)
md.push('')
const verdict = (key) => ADJ.items[key] ? `**${ADJ.items[key].verdict}** ${esc(ADJ.items[key].evidence)}` : ''
// features by area
const areas = {}
for (const j of all) for (const f of j.features) { (areas[f.area] ??= []).push({ ...f, cluster: j.cluster }) }
md.push('## Feature map by area (status counts)', '', '| area | built | half-built | planned | superseded | abandoned | unclear | total |', '|---|---|---|---|---|---|---|---|')
for (const a of Object.keys(areas).sort()) { const c = (s) => areas[a].filter((f) => f.status === s).length; md.push(`| ${a} | ${c('built')} | ${c('half-built')} | ${c('planned')} | ${c('superseded')} | ${c('abandoned')} | ${c('unclear')} | ${areas[a].length} |`) }
md.push('')
for (const a of Object.keys(areas).sort()) {
  md.push(`### ${a}`, '', '| feature | status | source | code | reader |', '|---|---|---|---|---|')
  for (const f of areas[a].sort((x, y) => x.status.localeCompare(y.status) || x.name.localeCompare(y.name))) md.push(`| ${esc(f.name)} | ${f.status} | ${esc(f.source)} | ${esc(f.codeEvidence)} | ${f.cluster} |`)
  md.push('')
}
md.push('## Half-built', '', '| area | item | doc says | code shows | gap | reader | verdict |', '|---|---|---|---|---|---|---|')
for (const j of all) j.halfBuilt.forEach((h, i) => md.push(`| ${h.area} | ${esc(h.item)} | ${esc(h.docSays)} | ${esc(h.codeShows)} | ${esc(h.gap)} | ${j.cluster} | ${verdict(`${j.cluster}/halfBuilt/${i}`)} |`))
md.push('', '## Contradictions', '')
for (const sev of ['blocking', 'material', 'cosmetic']) {
  md.push(`### ${sev}`, '', '| topic | A | B | reader | verdict |', '|---|---|---|---|---|')
  for (const j of all) j.contradictions.forEach((c, i) => { if (c.severity === sev) md.push(`| ${esc(c.topic)} | ${esc(c.a.cite)}: “${esc(c.a.claim)}” | ${esc(c.b.cite)}: “${esc(c.b.claim)}” | ${j.cluster} | ${verdict(`${j.cluster}/contradictions/${i}`)} |`) })
  md.push('')
}
md.push('## Open decisions', '', '| area | id | cite | question | reader |', '|---|---|---|---|---|')
for (const j of all) for (const o of [...j.openDecisions].sort((a, b) => a.area.localeCompare(b.area))) md.push(`| ${o.area} | ${esc(o.id)} | ${esc(o.cite)} | ${esc(o.question)} | ${j.cluster} |`)
md.push('', '## Superseded docs', '', '| doc | superseded by | cite | reader |', '|---|---|---|---|')
for (const j of all) for (const s of j.supersededDocs) md.push(`| ${esc(s.doc)} | ${esc(s.supersededBy)} | ${esc(s.cite)} | ${j.cluster} |`)
fs.writeFileSync(path.join(ROOT, 'docs/spec/inventory/SEMANTIC.md'), md.join('\n') + '\n')
const tot = (k) => all.reduce((n, j) => n + j[k].length, 0)
console.log(JSON.stringify({ readers: all.length, features: tot('features'), halfBuilt: tot('halfBuilt'), contradictions: tot('contradictions'), openDecisions: tot('openDecisions'), superseded: tot('supersededDocs'), areas: Object.keys(areas).length }))
