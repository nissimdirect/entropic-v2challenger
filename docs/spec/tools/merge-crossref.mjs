#!/usr/bin/env node
// merge-crossref.mjs — merge docs/spec/inventory/crossref/*.json (+ crossref-adjudications.json) → inventory/CROSSREF-SEMANTIC.md
//   node docs/spec/tools/merge-crossref.mjs
import fs from 'node:fs'
import path from 'node:path'

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../../..')
const DIR = path.join(ROOT, 'docs/spec/inventory/crossref')
const ADJ = path.join(ROOT, 'docs/spec/inventory/crossref-adjudications.json')
const adj = fs.existsSync(ADJ) ? JSON.parse(fs.readFileSync(ADJ, 'utf8')) : { readers: {}, items: {} }
const files = fs.readdirSync(DIR).filter((f) => f.endsWith('.json')).sort()
const all = files.map((f) => JSON.parse(fs.readFileSync(path.join(DIR, f), 'utf8')))
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')
const md = []
const t = (h, rows) => { md.push(`| ${h.join(' | ')} |`, `|${h.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.map(esc).join(' | ')} |`), '') }
const verdict = (id) => adj.items[id]?.verdict ?? 'unadjudicated'

const flat = (k) => all.flatMap((c) => (c[k] ?? []).map((x) => ({ ...x, cluster: c.cluster })))
const contradictions = flat('contradictions'), gaps = flat('gaps'), shared = flat('sharedResources'), chains = flat('supersedeChains'), oq = flat('openQuestions'), trace = flat('trace')
// de-dup contradictions that two readers found (same unordered cite pair)
const seen = new Map()
for (const c of contradictions) { const k = [c.a.cite, c.b.cite].sort().join(' ⇄ '); if (seen.has(k)) seen.get(k).alsoFoundBy.push(c.cluster); else seen.set(k, { ...c, alsoFoundBy: [] }) }
const uniq = [...seen.values()].filter((c) => verdict(c.id) !== 'refuted').map((c) => (adj.items[c.id]?.severity ? { ...c, severity: adj.items[c.id].severity, topic: `${c.topic} [severity set by orchestrator]` } : c))
const sevRank = { blocking: 0, material: 1, cosmetic: 2 }
uniq.sort((a, b) => (sevRank[a.severity] ?? 3) - (sevRank[b.severity] ?? 3) || String(a.topic).localeCompare(String(b.topic)))

md.push('# CROSS-REFERENCE — semantic layer (generated by tools/merge-crossref.mjs — do not hand-edit)', '')
md.push(`Readers: ${all.map((c) => c.cluster).join(', ')} · brief \`tools/crossref-brief.md\` · verdicts \`crossref-adjudications.json\`. Refuted items are dropped; everything else is shown with its verdict.`, '')
md.push('## Totals', '')
t(['cluster', 'docs read', 'trace', 'contradictions', 'blocking', 'gaps', 'shared', 'shared conflicts', 'chains', 'open Qs', 'reader trust'], all.map((c) => [c.cluster, c.docsRead?.length ?? 0, c.trace.length, c.contradictions.length, c.contradictions.filter((x) => x.severity === 'blocking').length, c.gaps.length, c.sharedResources.length, c.sharedResources.filter((x) => x.conflict).length, c.supersedeChains.length, c.openQuestions.length, adj.readers[c.cluster]?.policy ?? '—']))

md.push('## Trace matrix (UP/DOWN) — status per object', '')
const objs = [...new Set(trace.map((r) => r.object ?? '—'))].sort()
const sts = ['traced', 'no-law', 'no-code', 'no-test', 'orphan-code', 'stale-plan']
t(['object', ...sts, 'total'], objs.map((o) => { const rs = trace.filter((r) => (r.object ?? '—') === o); return [o, ...sts.map((s) => rs.filter((r) => r.status === s).length), rs.length] }))

md.push(`## ACROSS · contradictions (${uniq.length} after de-dup; refuted dropped)`, '')
t(['id', 'sev', 'axis', 'objects', 'topic', 'A', 'B', 'recommendation', 'verdict', 'known'], uniq.map((c) => [c.id + (c.alsoFoundBy.length ? ` (+${c.alsoFoundBy.join(',')})` : ''), c.severity, c.axis, (c.objects ?? []).join(' '), c.topic, `${c.a.cite} — “${String(c.a.claim).slice(0, 110)}”`, `${c.b.cite} — “${String(c.b.claim).slice(0, 110)}”`, c.recommendation, verdict(c.id) + (adj.items[c.id]?.note ? `: ${adj.items[c.id].note}` : ''), c.known ?? '']))

md.push('## ACROSS · shared resources with a conflict', '')
t(['kind', 'name', 'claimants', 'note', 'cluster'], shared.filter((s) => s.conflict).map((s) => [s.kind, s.name, s.claimants.map((c) => `${c.object}: ${c.meaning} @${c.cite}`).join(' ⏐ '), s.note, s.cluster]))

md.push('## Gaps', '')
const kinds = [...new Set(gaps.map((g) => g.kind))].sort()
for (const k of kinds) { md.push(`### ${k}`, ''); t(['object', 'item', 'evidence', 'cluster'], gaps.filter((g) => g.kind === k).map((g) => [g.object, g.item, g.evidence, g.cluster])) }

md.push('## Supersede chains (header missing = issue)', '')
t(['topic', 'chain', 'header present', 'cluster'], chains.sort((a, b) => Number(a.headerPresent) - Number(b.headerPresent)).map((c) => [c.topic, c.chain.join(' → '), c.headerPresent ? 'yes' : '**NO**', c.cluster]))

md.push('## Open questions (→ phase-5 batches)', '')
t(['objects', 'question', 'cites', 'cluster'], oq.map((q) => [(q.objects ?? []).join(' '), q.question, (q.cites ?? []).join(', '), q.cluster]))

md.push('## Full trace rows', '')
t(['object', 'item', 'law', 'plan', 'packet', 'code', 'test', 'status', 'note'], trace.map((r) => [r.object, r.item, r.law, r.plan, r.packet, r.code, r.test, r.status, r.note]))

// ---------- coverage oracle: every doc in the crossref universe is referenced by ≥1 reader (phase-1 semantic or crossref) ----------
const xref = JSON.parse(fs.readFileSync(path.join(ROOT, 'docs/spec/inventory/crossref.json'), 'utf8'))
const semDir = path.join(ROOT, 'docs/spec/inventory/semantic')
const blob = [...files.map((f) => fs.readFileSync(path.join(DIR, f), 'utf8')), ...fs.readdirSync(semDir).map((f) => fs.readFileSync(path.join(semDir, f), 'utf8'))].join('\n')
const EXEMPT = /^\.claude\/commands\/|^\.specify\/|^docs\/spec\//  // tooling + this pass's own output
const unreferenced = xref.docs.filter((d) => !EXEMPT.test(d.path) && !blob.includes(d.path))
md.push(`## Coverage oracle — docs no reader referenced (${unreferenced.length}; target 0; exempt: tooling + docs/spec/)`, '')
md.push(unreferenced.map((d) => `- ${d.path} (${d.kind}, ${d.lines} lines)`).join('\n') || '- none', '')

fs.writeFileSync(path.join(ROOT, 'docs/spec/inventory/CROSSREF-SEMANTIC.md'), md.join('\n'))
console.log(JSON.stringify({ unreferencedDocs: unreferenced.length, clusters: all.length, trace: trace.length, contradictions: contradictions.length, unique: uniq.length, blocking: uniq.filter((c) => c.severity === 'blocking').length, gaps: gaps.length, sharedConflicts: shared.filter((s) => s.conflict).length, chainsNoHeader: chains.filter((c) => !c.headerPresent).length, openQuestions: oq.length }))
